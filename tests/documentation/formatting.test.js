'use strict';
// Generated regions must survive `prettier --write`. Prettier inserts blank lines after
// HTML comments and re-pads table columns, so generated content sits inside a
// prettier-ignore range, which Prettier leaves byte-for-byte untouched.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {generate} = require('../../plugins/documentation/skills/documentation/scripts/generate');
const config = {version:1, sourceRoots:['src'], docsRoot:'docs', instruction:'CLAUDE.md', index:'docs/index.md', strict:false};
const START = '<!-- prettier-ignore-start -->', END = '<!-- prettier-ignore-end -->';
function put(root, name, content) { const file=path.join(root,name); fs.mkdirSync(path.dirname(file),{recursive:true}); fs.writeFileSync(file,content); }
function fixture(t, instruction) {
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'documentation-format-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  put(root,'documentation.config.json',JSON.stringify(config));
  put(root,'CLAUDE.md',instruction); put(root,'src/a.js','x');
  return root;
}
const region = (text, name) => new RegExp(`<!-- AUTO:${name} -->\\r?\\n([\\s\\S]*?)<!-- /AUTO:${name} -->`).exec(text)[1];

test('every generated instruction region is wrapped in a prettier-ignore range', t => {
  const root=fixture(t,'# P\n<!-- AUTO:tree -->\n<!-- /AUTO:tree -->\n<!-- AUTO:modules -->\n<!-- /AUTO:modules -->\n<!-- AUTO:docs -->\n<!-- /AUTO:docs -->\n');
  const output=generate(root).outputs['CLAUDE.md'];
  for (const name of ['tree','modules','docs']) {
    const body=region(output,name);
    assert.ok(body.startsWith(START+'\n'), `${name} opens the ignore range`);
    assert.ok(body.endsWith('\n'+END+'\n'), `${name} closes the ignore range`);
  }
  assert.ok(region(output,'docs').includes('[Documentation index](docs/index.md)'));
});

test('generated index keeps its ownership marker and ignores formatting below it', t => {
  const root=fixture(t,'<!-- AUTO:docs -->\n<!-- /AUTO:docs -->\n');
  const index=generate(root).outputs['docs/index.md'];
  const lines=index.split('\n');
  assert.equal(lines[0],'<!-- Generated by harness documentation; do not edit by hand. -->');
  assert.equal(lines[1],START);
  assert.equal(lines.at(-2),END); assert.equal(lines.at(-1),'');
});

test('refresh migrates a legacy unwrapped block and check then passes', t => {
  const legacy='Authored\n<!-- AUTO:docs -->\n[Documentation index](docs/index.md)\n<!-- /AUTO:docs -->\nTail\n';
  const root=fixture(t,legacy);
  assert.throws(()=>generate(root,{check:true}),/Stale generated documentation/);
  generate(root);
  const migrated=fs.readFileSync(path.join(root,'CLAUDE.md'),'utf8');
  assert.ok(migrated.startsWith('Authored\n') && migrated.endsWith('Tail\n'));
  assert.ok(region(migrated,'docs').startsWith(START));
  assert.doesNotThrow(()=>generate(root,{check:true}));
  assert.deepEqual(generate(root).outputs['CLAUDE.md'],migrated);
});

test('CRLF instruction files keep CRLF inside the ignore range', t => {
  const root=fixture(t,'A\r\n<!-- AUTO:docs -->\r\n<!-- /AUTO:docs -->\r\n');
  const output=generate(root).outputs['CLAUDE.md'];
  assert.ok(output.includes(`<!-- AUTO:docs -->\r\n${START}\r\n`));
  assert.ok(output.includes(`\r\n${END}\r\n<!-- /AUTO:docs -->`));
  assert.ok(!/[^\r]\n/.test(output));
});
